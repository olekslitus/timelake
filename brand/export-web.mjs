// Exports the current mark to the web app.
//   bun brand/export-web.mjs
// Writes dashboard/components/brand/mark-geometry.ts (for the inline <TimelakeMark/>) and
// dashboard/app/icon.svg (the favicon; black lines, white in dark browser themes).
import { mkdirSync, writeFileSync } from "node:fs"
import path from "node:path"

import { MARKS, WORDMARK, markLines } from "./marks.mjs"

const CURRENT = "v1"
const m = MARKS[CURRENT]
const root = path.join(import.meta.dir, "..", "dashboard")
const lines = markLines(m).map((pts) => pts.map(([x, y]) => `${+x.toFixed(2)},${+y.toFixed(2)}`).join(" "))

const ts = `// Generated by brand/export-web.mjs from brand/marks.mjs (mark ${CURRENT}). Do not edit; re-run the script.
export const MARK = {
  version: ${JSON.stringify(CURRENT)},
  clipRadius: ${m.r ?? 47},
  strokeWidth: ${m.width},
  lines: ${JSON.stringify(lines, null, 2).replace(/\n/g, "\n  ")},
} as const

export const WORDMARK = ${JSON.stringify(WORDMARK, null, 2)} as const
`
mkdirSync(path.join(root, "components/brand"), { recursive: true })
writeFileSync(path.join(root, "components/brand/mark-geometry.ts"), ts)

const icon =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><style>g{stroke:#000}@media (prefers-color-scheme:dark){g{stroke:#fff}}</style>` +
  `<defs><clipPath id="c"><circle cx="50" cy="50" r="${m.r ?? 47}"/></clipPath></defs>` +
  `<g clip-path="url(#c)" fill="none" stroke-width="${m.width}" stroke-linejoin="miter" stroke-miterlimit="12" stroke-linecap="butt">` +
  lines.map((p) => `<polyline points="${p}"/>`).join("") +
  `</g></svg>\n`
writeFileSync(path.join(root, "app/icon.svg"), icon)
console.log("wrote dashboard/components/brand/mark-geometry.ts and dashboard/app/icon.svg")

#!/usr/bin/env bash
# Builds crates/timelake-wasm and embeds it into src/wasm/ (glue JS + the module inlined as base64,
# so the package loads the same way in browsers, Node, bundlers and serverless functions).
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$(cd ../.. && pwd)
TARGET=$ROOT/target
(cd "$ROOT/crates/timelake-wasm" && CARGO_TARGET_DIR="$TARGET" cargo build --release --target wasm32-unknown-unknown)
rm -rf src/wasm && mkdir -p src/wasm
wasm-bindgen --target web --out-dir src/wasm --out-name timelake_wasm "$TARGET/wasm32-unknown-unknown/release/timelake_wasm.wasm"
bunx wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext --enable-mutable-globals \
  src/wasm/timelake_wasm_bg.wasm -o src/wasm/timelake_wasm_bg.wasm
bun -e '
const fs = require("fs")
const b = fs.readFileSync("src/wasm/timelake_wasm_bg.wasm")
fs.writeFileSync("src/wasm/inline.js", "// Generated by scripts/build-wasm.sh\nexport const wasmBase64 = \"" + b.toString("base64") + "\";\n")
fs.writeFileSync("src/wasm/inline.d.ts", "export declare const wasmBase64: string;\n")
console.log("wasm:", (b.length / 1e6).toFixed(2), "MB")
'
rm src/wasm/timelake_wasm_bg.wasm src/wasm/timelake_wasm_bg.wasm.d.ts
# The module is always passed in (inlined), so drop the glue's fetch-by-URL default: bundlers would
# otherwise try to resolve a .wasm file that is not shipped.
perl -0pi -e "s/module_or_path = new URL\('timelake_wasm_bg\.wasm', import\.meta\.url\);/throw new Error('@timelake\/client: the WASM module is inlined; call initSync');/" src/wasm/timelake_wasm.js
grep -q "import.meta.url" src/wasm/timelake_wasm.js && { echo "glue still references import.meta.url" >&2; exit 1; } || true

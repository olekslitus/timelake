#!/usr/bin/env bash
# Builds crates/timelake-wasm and embeds it into src/wasm/ (glue JS + the module inlined as base64,
# so the package loads the same way in browsers, Node, bundlers and serverless functions).
#
#   scripts/build-wasm.sh            build and embed
#   scripts/build-wasm.sh --check    fail if src/wasm/inline.js was built from other sources
#
# Needs the wasm-bindgen CLI at the crate's exact wasm-bindgen version, and for zstd (C) a clang
# that targets wasm32 plus llvm-ar. CC_wasm32_unknown_unknown and AR_wasm32_unknown_unknown choose
# them; by default Homebrew's LLVM when it is installed, else clang and llvm-ar from PATH.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$(cd ../.. && pwd)
CRATE=$ROOT/crates/timelake-wasm
HASH=$(bun scripts/wasm-hash.mjs)

if [ "${1:-}" = "--check" ]; then
  BUILT=$(head -n 1 src/wasm/inline.js | sed -nE 's/.*sources ([0-9a-f]{64}).*/\1/p')
  if [ "$BUILT" != "$HASH" ]; then
    echo "src/wasm/inline.js is stale (built from ${BUILT:-unknown sources}, sources are now $HASH)." >&2
    echo "Run: bun run build:wasm (in packages/timelake-client)" >&2
    exit 1
  fi
  echo "src/wasm/inline.js matches its sources ($HASH)"
  exit 0
fi

WANT=$(awk '$0 == "name = \"wasm-bindgen\"" { getline; gsub(/version = |"/, ""); print; exit }' "$CRATE/Cargo.lock")
HAVE=$(wasm-bindgen --version 2>/dev/null | awk '{ print $2 }' || true)
if [ "$HAVE" != "$WANT" ]; then
  echo "wasm-bindgen CLI ${HAVE:-not found}, but the crate uses wasm-bindgen $WANT." >&2
  echo "Install it with: cargo install wasm-bindgen-cli --version $WANT --locked" >&2
  exit 1
fi

if [ -z "${CC_wasm32_unknown_unknown:-}" ] && LLVM=$(brew --prefix llvm 2>/dev/null) && [ -x "$LLVM/bin/clang" ]; then
  export CC_wasm32_unknown_unknown=$LLVM/bin/clang
  export AR_wasm32_unknown_unknown=${AR_wasm32_unknown_unknown:-$LLVM/bin/llvm-ar}
fi

TARGET=$ROOT/target
(cd "$CRATE" && CARGO_TARGET_DIR="$TARGET" cargo build --release --target wasm32-unknown-unknown)
rm -rf src/wasm && mkdir -p src/wasm
wasm-bindgen --target web --out-dir src/wasm --out-name timelake_wasm "$TARGET/wasm32-unknown-unknown/release/timelake_wasm.wasm"
# The features rustc enables for wasm32-unknown-unknown, so wasm-opt may keep and use them.
bunx wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext --enable-mutable-globals \
  --enable-reference-types --enable-multivalue src/wasm/timelake_wasm_bg.wasm -o src/wasm/timelake_wasm_bg.wasm
WASM_HASH=$HASH bun -e '
const fs = require("fs")
const b = fs.readFileSync("src/wasm/timelake_wasm_bg.wasm")
const header = `// Generated by scripts/build-wasm.sh from sources ${process.env.WASM_HASH} (scripts/wasm-hash.mjs)\n`
fs.writeFileSync("src/wasm/inline.js", header + "export const wasmBase64 = \"" + b.toString("base64") + "\";\n")
fs.writeFileSync("src/wasm/inline.d.ts", "export declare const wasmBase64: string;\n")
console.log("wasm:", (b.length / 1e6).toFixed(2), "MB")
'
rm src/wasm/timelake_wasm_bg.wasm src/wasm/timelake_wasm_bg.wasm.d.ts
# The module is always passed in (inlined), so drop the glue's fetch-by-URL default: bundlers would
# otherwise try to resolve a .wasm file that is not shipped.
perl -0pi -e "s/module_or_path = new URL\('timelake_wasm_bg\.wasm', import\.meta\.url\);/throw new Error('@timelake\/client: the WASM module is inlined; call initSync');/" src/wasm/timelake_wasm.js
if grep -q "import.meta.url" src/wasm/timelake_wasm.js; then
  echo "glue still references import.meta.url" >&2
  exit 1
fi
